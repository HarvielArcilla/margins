// Copies the bundled reading fonts out of their @fontsource packages into
// src/renderer/fonts and writes the catalogue the app reads (fonts.json).
// Runs before `npm start` and before packaging; the output is not committed.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = path.join(root, 'src', 'renderer', 'fonts');

// id: @fontsource package name. category groups them in the font picker.
const FONTS = [
  ['literata', 'Literata', 'serif', 'Designed for long-form reading on screens'],
  ['merriweather', 'Merriweather', 'serif', 'Sturdy and very readable at small sizes'],
  ['lora', 'Lora', 'serif', 'Calligraphic, warm, contemporary'],
  ['eb-garamond', 'EB Garamond', 'serif', 'Classic old-style book face'],
  ['crimson-pro', 'Crimson Pro', 'serif', 'Elegant old-style for novels'],
  ['source-serif-4', 'Source Serif 4', 'serif', 'Transitional, crisp, neutral'],
  ['libre-baskerville', 'Libre Baskerville', 'serif', 'Baskerville tuned for screens'],
  ['libre-caslon-text', 'Libre Caslon Text', 'serif', 'Caslon revival, bookish'],
  ['noto-serif', 'Noto Serif', 'serif', 'Wide language coverage'],
  ['pt-serif', 'PT Serif', 'serif', 'Russian-school transitional serif'],
  ['spectral', 'Spectral', 'serif', 'Thin, elegant, made for screens'],
  ['alegreya', 'Alegreya', 'serif', 'Dynamic, literary rhythm'],
  ['vollkorn', 'Vollkorn', 'serif', 'Dark and hearty body text'],
  ['cormorant-garamond', 'Cormorant Garamond', 'serif', 'Display-leaning Garamond'],
  ['newsreader', 'Newsreader', 'serif', 'Editorial serif for long reads'],
  ['fraunces', 'Fraunces', 'serif', 'Soft "Old Style" with character'],
  ['ibm-plex-serif', 'IBM Plex Serif', 'serif', 'Engineered, modern serif'],
  ['gentium-book-plus', 'Gentium Book Plus', 'serif', 'Scholarly, multilingual'],
  ['playfair-display', 'Playfair Display', 'serif', 'High-contrast, dramatic'],
  ['bitter', 'Bitter', 'slab', 'Slab serif made for screens'],
  ['roboto-slab', 'Roboto Slab', 'slab', 'Geometric slab'],
  ['inter', 'Inter', 'sans', 'Neutral UI sans'],
  ['source-sans-3', 'Source Sans 3', 'sans', 'Humanist sans, clean'],
  ['ibm-plex-sans', 'IBM Plex Sans', 'sans', 'Grotesque with personality'],
  ['fira-sans', 'Fira Sans', 'sans', 'Humanist, open forms'],
  ['nunito', 'Nunito', 'sans', 'Rounded and friendly'],
  ['atkinson-hyperlegible', 'Atkinson Hyperlegible', 'accessible', 'Maximum letter distinction for low vision'],
  ['lexend', 'Lexend', 'accessible', 'Widened spacing to reduce visual stress'],
  ['opendyslexic', 'OpenDyslexic', 'accessible', 'Weighted bottoms for dyslexic readers'],
  ['andika', 'Andika', 'accessible', 'Clear letterforms for beginning readers'],
  ['jetbrains-mono', 'JetBrains Mono', 'mono', 'Monospaced'],
];

const WEIGHTS = [300, 400, 500, 600, 700];
const SUBSETS = ['latin', 'latin-ext'];
const RANGES = {
  latin: 'U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD',
  'latin-ext': 'U+0100-02BA, U+02BD-02C5, U+02C7-02CC, U+02CE-02D7, U+02DD-02FF, U+0304, U+0308, U+0329, U+1D00-1DBF, U+1E00-1E9F, U+1EF2-1EFF, U+2020, U+20A0-20AB, U+20AD-20C0, U+2113, U+2C60-2C7F, U+A720-A7FF',
};

fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(outDir, { recursive: true });

const catalogue = [];
let css = '/* Generated by scripts/build-fonts.mjs */\n';

for (const [id, name, category, blurb] of FONTS) {
  const pkg = path.join(root, 'node_modules', '@fontsource', id);
  const files = path.join(pkg, 'files');
  if (!fs.existsSync(files)) { console.warn(`skip ${id}: not installed`); continue; }
  const weights = new Set();
  let italic = false;
  for (const subset of SUBSETS) {
    for (const w of WEIGHTS) {
      for (const style of ['normal', 'italic']) {
        const file = `${id}-${subset}-${w}-${style}.woff2`;
        const src = path.join(files, file);
        if (!fs.existsSync(src)) continue;
        fs.copyFileSync(src, path.join(outDir, file));
        weights.add(w);
        if (style === 'italic') italic = true;
        css += `@font-face{font-family:"${name}";font-style:${style};font-weight:${w};font-display:swap;` +
          `src:url("app://reader/fonts/${file}") format("woff2");unicode-range:${RANGES[subset]};}\n`;
      }
    }
  }
  const license = ['LICENSE', 'LICENSE.md', 'OFL.txt'].map((f) => path.join(pkg, f)).find(fs.existsSync);
  if (license) fs.copyFileSync(license, path.join(outDir, `${id}.LICENSE.txt`));
  catalogue.push({ id, name, category, blurb, weights: [...weights].sort(), italic });
}

fs.writeFileSync(path.join(outDir, 'fonts.css'), css);
fs.writeFileSync(path.join(outDir, 'fonts.json'), JSON.stringify(catalogue, null, 2));
console.log(`bundled ${catalogue.length} fonts into src/renderer/fonts`);
